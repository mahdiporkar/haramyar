package ir.haramyar.rozeh.application.command;

import ir.haramyar.rozeh.domain.model.BookingActor;
import java.time.Instant;
import java.time.ZoneId;
import java.util.UUID;

/**
 * Application commands of the Rozeh Booking context. The acting {@link BookingActor} is always derived from the
 * secured request context by the interface layer, never taken from request bodies. {@code expectedVersion} is an
 * optional optimistic-concurrency guard supplied by clients that display a booking before changing it.
 */
public final class BookingCommands {
  private BookingCommands() {}

  /**
   * @param clientRequestId idempotency key generated by the client per submission attempt; resubmitting the same key
   *     returns the booking created by the first attempt
   * @param actorMobileVerified whether the identity provider reports verified ownership of the actor's mobile number
   */
  public record RequestBooking(BookingActor actor, boolean actorMobileVerified, UUID clientRequestId, String hostName, String hostPhone,
      String city, String area, String address, String category, String audience, String deliveryMode, Integer approximateCapacity, String notes,
      Instant startsAt, int durationMinutes, ZoneId timeZone) {}

  public record AcceptBooking(BookingActor actor, UUID bookingId, Long expectedVersion, String note) {}
  public record RejectBooking(BookingActor actor, UUID bookingId, Long expectedVersion, String reason) {}
  public record AssignProvider(BookingActor actor, UUID bookingId, Long expectedVersion, UUID providerId) {}
  public record ConfirmBooking(BookingActor actor, UUID bookingId, Long expectedVersion) {}
  public record CancelBooking(BookingActor actor, UUID bookingId, Long expectedVersion, String reason) {}
  public record CompleteBooking(BookingActor actor, UUID bookingId, Long expectedVersion) {}

  public record RegisterProvider(String displayName) {}
  public record UpdateProvider(UUID providerId, long expectedVersion, String displayName, Boolean active) {}
}
